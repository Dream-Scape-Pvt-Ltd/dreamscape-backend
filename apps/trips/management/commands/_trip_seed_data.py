def day(n, title, description, stay, elevation=None, acc="TEAHOUSE", acclim=False, meals=BLD, ll=None):
    return {
        "day_number": n,
        "title": title,
        "description": description,
        "overnight_stay": stay,
        "elevation_meters": elevation,
        "accommodation_type": acc,
        "is_acclimatization_day": acclim,
        "meals_included": meals,
        "latitude": ll[0] if ll else None,
        "longitude": ll[1] if ll else None,
    }


